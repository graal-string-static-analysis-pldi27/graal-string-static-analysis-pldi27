package gg.jte.bench;

import gg.jte.ContentType;
import gg.jte.TemplateEngine;
import gg.jte.TemplateOutputTest;
import gg.jte.benchmark.WelcomePage;
import gg.jte.html.OwaspHtmlTemplateOutput;
import gg.jte.output.StringOutput;
import gg.jte.output.Utf8ByteOutput;

/**
 * C96 jte phase 2: the render variants, shared by the JMH benchmark (JteBench) and the census main (Census), so both
 * programs run the same code. Each variant returns its concrete result type (no Object/Supplier indirection).
 * Templates: package gg.jte.generated.s (String static content) and gg.jte.generated.b (binaryStaticContent), both
 * generated by Gen from the upstream benchmark templates.
 */
public final class Variants {
    public static final String PKG_S = "gg.jte.generated.s";
    public static final String PKG_B = "gg.jte.generated.b";

    private final TemplateEngine engineS = TemplateEngine.createPrecompiled(null, ContentType.Html, null, PKG_S);
    private final TemplateEngine engineB = TemplateEngine.createPrecompiled(null, ContentType.Html, null, PKG_B);

    /** upstream test/jte-benchmark TemplateOutputTest.templateOutput (hand-written Plain-mode template, StringOutput). */
    public String upstreamTemplateOutput() {
        StringOutput output = new StringOutput();
        TemplateOutputTest.JtewelcomeGenerated_TemplateOutput.render(output, null, new TemplateOutputTest.WelcomePage(42));
        return output.toString();
    }

    /** upstream test/jte-benchmark TemplateOutputTest.stringBuilder (the same template on a raw StringBuilder). */
    public String upstreamStringBuilder() {
        StringBuilder output = new StringBuilder(8 * 1024);
        TemplateOutputTest.JtewelcomeGenerated_StringBuilder.render(output, null, new TemplateOutputTest.WelcomePage(42));
        return output.toString();
    }

    /** upstream jte Benchmark.render (precompiled Html engine, reflective Template.render) + the result String. */
    public String engineString() {
        StringOutput output = new StringOutput();
        engineS.render("welcome.jte", new WelcomePage(42), output);
        return output.toString();
    }

    /** upstream jte Benchmark_Binary.render (binaryStaticContent, Utf8ByteOutput). */
    public Utf8ByteOutput engineUtf8() {
        Utf8ByteOutput output = new Utf8ByteOutput();
        engineB.render("welcome.jte", new WelcomePage(42), output);
        return output;
    }

    /** engineString without the reflective dispatch: a direct call of the generated render method. */
    public String directString() {
        StringOutput output = new StringOutput();
        gg.jte.generated.s.JtewelcomeGenerated.render(new OwaspHtmlTemplateOutput(output), null, new WelcomePage(42));
        return output.toString();
    }

    /** NOT upstream: engineString with escapable page data (EscPage). */
    public String engineStringEsc() {
        StringOutput output = new StringOutput();
        engineS.render("welcome.jte", new EscPage(42), output);
        return output.toString();
    }

    /** NOT upstream: engineUtf8 with escapable page data (EscPage): Utf8ByteOutput substring + getBytes. */
    public Utf8ByteOutput engineUtf8Esc() {
        Utf8ByteOutput output = new Utf8ByteOutput();
        engineB.render("welcome.jte", new EscPage(42), output);
        return output;
    }
}
